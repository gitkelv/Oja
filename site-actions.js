// Registers Ọjà's own operations with the agent runtime.
// agent-manifest.json loads this module through "actions.module". Only the names listed
// in "actions.agentTools" become model tools, called website_<name>.
//
// Ọjà has one rule that shapes this file: a number shown to a buyer must be computed,
// not generated. Language models are poor arithmetic engines and a wrong total here is
// a buyer committing millions of naira on a bad figure. So every multiplication,
// every total and every spread is done in JavaScript and handed back to the agent.

import { Board } from "./board.js";

/**
 * Ọjà's site actions: arithmetic the agents must not do themselves, and the
 * quote board the page renders.
 */
class SiteActions {
  /**
   * Register every site action with the runtime.
   *
   * :param actions: The runtime registry facade with a register(definition) method.
   */
  static registerActions(actions) {
    actions.register(SiteActions.computeOrderTotalAction());
    actions.register(SiteActions.recordQuoteAction());
    actions.register(SiteActions.compareQuotesAction());
  }

  // --- order total ----------------------------------------------------------

  /**
   * Describe the arithmetic action. The comparison agent is told to call this
   * instead of multiplying, so a buyer never sees a model-generated total.
   *
   * :return: The action definition.
   */
  static computeOrderTotalAction() {
    return {
      name: "compute_order_total",
      description:
        "Work out the cost of a quantity at a unit price, with optional delivery. Call this for every total you report. Never multiply a price by a quantity yourself: a wrong total here means a buyer commits millions of naira on a bad figure.",
      effect: "read",
      inputSchema: {
        type: "object",
        properties: {
          unit_price_naira: { type: "number", description: "Price of one unit in naira." },
          quantity: { type: "number", description: "How many units the buyer asked for." },
          delivery_naira: { type: "number", description: "Delivery charge in naira, or 0 for collection." },
        },
        required: ["unit_price_naira", "quantity"],
        additionalProperties: false,
      },
      execute: SiteActions.computeOrderTotal,
    };
  }

  /**
   * Multiply a unit price by a quantity and add delivery.
   *
   * :param args: unit_price_naira, quantity and optional delivery_naira.
   * :return: The goods cost, delivery and total, or a refusal.
   */
  static computeOrderTotal({ unit_price_naira, quantity, delivery_naira = 0 }) {
    if (!Number.isFinite(unit_price_naira) || unit_price_naira <= 0) {
      return { ok: false, reason: "Unit price must be a positive number.", field: "unit_price_naira" };
    }
    if (!Number.isFinite(quantity) || quantity <= 0) {
      return { ok: false, reason: "Quantity must be a positive number.", field: "quantity" };
    }
    if (!Number.isFinite(delivery_naira) || delivery_naira < 0) {
      return { ok: false, reason: "Delivery must be zero or a positive number.", field: "delivery_naira" };
    }
    const goods = Math.round(unit_price_naira * quantity);
    const total = goods + Math.round(delivery_naira);
    return {
      ok: true,
      goods_naira: goods,
      delivery_naira: Math.round(delivery_naira),
      total_naira: total,
      formatted: `₦${total.toLocaleString("en-NG")}`,
      note: "Computed on this page, not generated by a model.",
    };
  }

  // --- quote board ----------------------------------------------------------

  /**
   * Describe the action that puts one dealer's answer on the board.
   *
   * :return: The action definition.
   */
  static recordQuoteAction() {
    return {
      name: "record_quote",
      description:
        "Put one dealer's answer on the quote board so the buyer can see it. Call this once for each dealer as soon as that dealer answers, before you have heard from the others.\n\nanswered is about whether the dealer replied, NOT about whether you liked the reply. Set it true whenever the dealer gave you a price, even if it cannot deliver to the buyer's location, even if the quantity is below its minimum, and even if it only quoted collection. Put that limitation in the delivery field, where the buyer needs it. Set answered false only when the dealer could not be reached at all, refused to quote, or does not carry the material.",
      effect: "write",
      inputSchema: {
        type: "object",
        properties: {
          dealer: { type: "string", description: "The dealer's business name only, with no address. 'Ilara Depot', not 'Ilara Depot, Ilara Junction, Lagos State'." },
          answered: { type: "boolean", description: "True if the dealer gave a price, even one you cannot use. False only if it could not be reached, refused, or does not carry the material." },
          material: { type: "string", description: "What was quoted, e.g. Dangote cement 50kg bag." },
          unit_price_naira: { type: "number", description: "Price of one unit in naira, as the dealer stated it." },
          unit: { type: "string", description: "What one unit is, e.g. bag, length, tonne, block." },
          minimum_order: { type: "string", description: "The dealer's stated minimum order." },
          delivery: { type: "string", description: "Delivery charge and window as the dealer stated it. If the dealer cannot deliver to the buyer's location, say so here plainly: that is the most useful thing on the card." },
          price_date: { type: "string", description: "The date the dealer said the price was good for." },
          note: { type: "string", description: "Anything else the dealer said, or why it did not answer." },
        },
        required: ["dealer", "answered"],
        additionalProperties: false,
      },
      execute: SiteActions.recordQuote,
    };
  }

  /**
   * Add a dealer's answer to the board.
   *
   * :param args: One dealer's quote fields.
   * :return: Confirmation, or a refusal when the dealer name is missing.
   */
  static recordQuote(args) {
    if (!args.dealer || !String(args.dealer).trim()) {
      return { ok: false, reason: "A quote needs the dealer's name.", field: "dealer" };
    }
    // A price can only come from a dealer that was actually reached, and a dealer
    // is only reached after the visitor approves the contact. A model that fills
    // the wait with a plausible answer would publish an invented price under a real
    // dealer's name, which is the one thing this product must never do.
    const priced = Number.isFinite(args.unit_price_naira) && args.unit_price_naira > 0;
    if (priced && !Board.isApproved(args.dealer)) {
      return {
        ok: false,
        reason:
          `Refused: ${args.dealer} has not been contacted yet, so there is no price to record. ` +
          "Wait for that dealer's own answer. Never write a price, a minimum order, a delivery term or a date that a dealer did not give you in this conversation.",
        field: "dealer",
      };
    }
    Board.addQuote(args);
    return { ok: true, on_board: Board.count(), note: "Shown on the quote board." };
  }

  // --- spread ---------------------------------------------------------------

  /**
   * Describe the spread action. Ọjà never averages, so this returns the range
   * and the gap, never a midpoint.
   *
   * :return: The action definition.
   */
  static compareQuotesAction() {
    return {
      name: "compare_quotes",
      description:
        "Work out the spread across every quote on the board: lowest, highest and the gap between them. Call this after recording all dealer answers. It deliberately does not return an average or a typical price, because averaging contradictory dealer prices is the thing that makes existing Nigerian price lists useless.",
      effect: "read",
      inputSchema: { type: "object", properties: {}, additionalProperties: false },
      execute: SiteActions.compareQuotes,
    };
  }

  /**
   * Work out the lowest, highest and gap across recorded quotes.
   *
   * :return: The spread, or a note that there is not enough to compare.
   */
  static compareQuotes() {
    // A price counts whether or not the dealer could deliver. Excluding a quote the
    // buyer cannot use would hide the most useful fact on the board: that the
    // cheapest price belongs to a dealer who cannot reach him.
    const priced = Board.quotes().filter(
      (q) => Number.isFinite(q.unit_price_naira) && q.unit_price_naira > 0,
    );
    if (priced.length === 0) {
      return { ok: true, comparable: 0, note: "No dealer returned a price, so there is nothing to compare." };
    }
    if (priced.length === 1) {
      return {
        ok: true,
        comparable: 1,
        note: "Only one dealer returned a price. A single quote is not a comparison: say so.",
        only: { dealer: priced[0].dealer, unit_price_naira: priced[0].unit_price_naira },
      };
    }
    const sorted = [...priced].sort((a, b) => a.unit_price_naira - b.unit_price_naira);
    const low = sorted[0];
    const high = sorted[sorted.length - 1];
    const gap = high.unit_price_naira - low.unit_price_naira;
    const gapPercent = Math.round((gap / low.unit_price_naira) * 1000) / 10;
    Board.setSpread({ low, high, gap, gapPercent });
    return {
      ok: true,
      comparable: priced.length,
      lowest: { dealer: low.dealer, unit_price_naira: low.unit_price_naira },
      highest: { dealer: high.dealer, unit_price_naira: high.unit_price_naira },
      gap_naira: gap,
      gap_percent: gapPercent,
      material_disagreement: gapPercent > 10,
      note:
        gapPercent > 10
          ? "The dealers disagree by more than ten per cent. Tell the buyer that plainly: the disagreement is the finding."
          : "Report each dealer separately. Do not state an average or a typical price.",
    };
  }
}

// The runtime calls the module's registerActions export. The methods above all
// reference SiteActions by name rather than through `this`, so the function works
// detached from the class.
export const registerActions = SiteActions.registerActions;
export { SiteActions };
